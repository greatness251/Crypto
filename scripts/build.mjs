import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');

// Ordered dependency graph so classic <script defer> works on both file:// and http://
const moduleOrder = [
  'js/utils/formatters.js',
  'js/data/cryptoApps.js',
  'js/state/store.js',
  'js/api/cryptoService.js',
  'js/components/navbar.js',
  'js/components/searchBar.js',
  'js/components/sparkline.js',
  'js/components/coinSpotlight.js',
  'js/components/marketGrid.js',
  'js/components/appsHub.js',
  'js/main.js'
];

function stripModuleSyntax(code) {
  return code
    // Remove single-line and multi-line import statements
    .replace(/^import\s+[\s\S]*?from\s+['"][^'"]+['"];?\r?\n?/gm, '')
    // Strip export keywords while preserving declarations
    .replace(/^export\s+(?=(?:async\s+)?function\b|const\b|let\b|var\b|class\b)/gm, '');
}

const chunks = moduleOrder.map((relPath) => {
  const fullPath = path.join(rootDir, relPath);
  const raw = fs.readFileSync(fullPath, 'utf8');
  const cleaned = stripModuleSyntax(raw).trim();
  return `// --- ${relPath} ---\n${cleaned}`;
});

const bundle = `/* Auto-generated by scripts/build.mjs — runs cleanly on both http:// and file:// */\n(function () {\n  'use strict';\n\n${chunks.join('\n\n')}\n})();\n`;

const outPath = path.join(rootDir, 'js/app.bundle.js');
fs.writeFileSync(outPath, bundle, 'utf8');
console.log(`Built ${outPath} (${bundle.length} bytes)`);
